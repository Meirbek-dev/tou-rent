/**
 * Открытая вкладка - в адресе страницы, а не в состоянии компонента.
 *
 * Экраны ведения тендера собраны из десятка разделов, и вкладка решает,
 * какой из них виден. Держи ее в `useState` - и ссылка «посмотри вкладку
 * протоколов» перестала бы существовать, обновление страницы возвращало бы
 * к обзору, а кнопка «назад» уводила бы с экрана целиком вместо возврата к
 * предыдущей вкладке.
 *
 * Неизвестное значение молча выбрасывается: адрес приходит извне, ошибаться
 * в нем - обычное дело, а пустой экран за это наказывал бы читателя. По той
 * же причине параметр необязательный - иначе каждая ссылка на страницу
 * обязана была бы называть вкладку, включая ссылки из реестров и
 * уведомлений, которым до вкладок дела нет.
 */
export function tabSearch<T extends string>(
  allowed: readonly T[]
): (search: Record<string, unknown>) => { tab?: T } {
  return (search) => {
    const known = allowed.find((tab) => tab === search["tab"])
    return known === undefined ? {} : { tab: known }
  }
}
