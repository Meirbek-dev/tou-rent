-- Заголовок публикации особого порядка на казахском и английском (NFR-01).
--
-- Заголовок материала собирается в момент публикации из подписи категории
-- (`refdata.special_categories`) и с этого мгновения хранится строкой: досье
-- решения должно показывать то, что было опубликовано, а не то, что сейчас
-- в справочнике. Строка была одна и русская, поэтому реестр публикаций на
-- /kk/ и /en/ читался по-русски - единственный экран портала, куда перевод
-- не доходил в принципе.
--
-- Столбцы nullable: у материалов, опубликованных до этой миграции, перевода
-- нет и взять его неоткуда - подпись категории с тех пор могла измениться.
-- Пустое значение означает «перевода нет», и подставляет русский заголовок
-- кабинет, а не сервер.
ALTER TABLE core.public_records
  ADD COLUMN IF NOT EXISTS title_kk text,
  ADD COLUMN IF NOT EXISTS title_en text;

COMMENT ON COLUMN core.public_records.title_kk IS
  'Заголовок материала на казахском; NULL - перевода нет (NFR-01)';
COMMENT ON COLUMN core.public_records.title_en IS
  'Заголовок материала на английском; NULL - перевода нет (NFR-01)';
