import { toast } from "@/components/ui/toast"

/**
 * Всплывающее сообщение об исходе действия.
 *
 * Тонкая обертка над менеджером Base UI намеренно: вызывающему нужно знать
 * одно - «получилось» или «не получилось», - а не форму объекта тоста.
 * Пока обертки не было, единственным способом сообщить об успехе оставалось
 * молчание: экран просто перерисовывался, и пользователь гадал, прошла ли
 * мутация. Отказ по-прежнему дублируется на месте (`FormAlert` у формы):
 * тост исчезает, а причина отказа должна остаться на экране.
 *
 * `<Toaster />` смонтирован один раз в каркасе кабинетов
 * (`routes/app/route.tsx`) - менеджер здесь тот же самый, модульный.
 */
export function notifySuccess(message: string): void {
  toast.add({ title: message, type: "success" })
}

export function notifyError(message: string): void {
  // Отказ живет дольше успеха: его читают, а не замечают краем глаза
  toast.add({ title: message, type: "error", timeout: 8000 })
}
